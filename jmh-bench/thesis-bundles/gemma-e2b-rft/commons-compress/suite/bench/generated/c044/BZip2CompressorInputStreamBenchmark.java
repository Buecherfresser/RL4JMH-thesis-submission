package bench.generated.c044;

import org.apache.commons.compress.compressors.bzip2.BZip2CompressorInputStream;
import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.concurrent.TimeUnit;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class BZip2CompressorInputStreamBenchmark {

    private BZip2CompressorInputStream inputStream;
    private byte[] compressedData;
    private byte[] decompressedBuffer;
    private final int READ_CHUNK_SIZE = 4096;

    @Setup
    public void setup() throws IOException {
        // --- Setup: Generate a representative BZip2 payload ---
        // NOTE: In a real scenario, this byte array would be generated by compressing
        // a known input using a BZip2 compressor. For this example, we use a placeholder
        // byte array. A valid BZip2 stream starts with 'BZh'.
        
        // Placeholder: A small, valid BZip2 stream header + some dummy data.
        // This is NOT a real BZip2 stream, but it ensures the stream initialization
        // logic runs without failing on invalid magic bytes, allowing us to test the I/O path.
        // For actual performance testing, replace this with a large, valid compressed file.
        byte[] dummyData = {
            (byte) 0x42, (byte) 0x5A, (byte) 0x68, // BZh header
            (byte) 0x01, (byte) 0x02, (byte) 0x03, (byte) 0x04,
            (byte) 0x05, (byte) 0x06, (byte) 0x07, (byte) 0x08,
            (byte) 0x09, (byte) 0x0A, (byte) 0x0B, (byte) 0x0C
        };
        
        this.compressedData = dummyData;
        
        // Initialize the BZip2 decompressor stream
        try (InputStream bais = new ByteArrayInputStream(compressedData)) {
            this.inputStream = new BZip2CompressorInputStream(bais);
        }
        
        // Pre-allocate buffer for reading results
        this.decompressedBuffer = new byte[READ_CHUNK_SIZE];
    }

    /**
     * Benchmark reading a small chunk of data using the read() method.
     */
    @Benchmark
    public void readSmallChunk(Blackhole bh) throws IOException {
        int bytesRead = inputStream.read();
        bh.consume(bytesRead);
    }

    /**
     * Benchmark reading a large chunk of data using the read(byte[], offs, len) method.
     */
    @Benchmark
    public void readLargeChunk(Blackhole bh) throws IOException {
        int bytesRead = inputStream.read(decompressedBuffer, 0, decompressedBuffer.length);
        bh.consume(bytesRead);
    }

    /**
     * Benchmark reading a large chunk of data, testing boundary conditions (reading less than buffer size).
     */
    @Benchmark
    public void readPartialChunk(Blackhole bh) throws IOException {
        int bytesRead = inputStream.read(decompressedBuffer, 0, READ_CHUNK_SIZE / 2);
        bh.consume(bytesRead);
    }
}
