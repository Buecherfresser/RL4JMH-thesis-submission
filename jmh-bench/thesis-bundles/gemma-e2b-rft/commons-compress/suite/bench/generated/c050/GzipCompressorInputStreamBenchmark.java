package bench.generated.c050;

import org.apache.commons.compress.compressors.gzip.GzipCompressorInputStream;
import org.apache.commons.io.IOUtils;
import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.concurrent.TimeUnit;
import java.util.zip.GZIPOutputStream;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class GzipCompressorInputStreamBenchmark {

    private byte[] compressedData;
    private ByteArrayInputStream inputStream;

    // --- Setup ---
    @Setup
    public void setup() throws IOException {
        // 1. Create a representative GZIP payload.
        // This payload is generated by compressing a simple string.
        String originalString = "This is a test string used for GZIP decompression benchmarking. " +
                                "We need enough data to ensure the stream processing logic is exercised. " +
                                "Repeat this to make the payload substantial.";
        
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        try (GZIPOutputStream gzip = new GZIPOutputStream(baos)) {
            gzip.write(originalString.getBytes("UTF-8"));
        }
        compressedData = baos.toByteArray();
        
        // 2. Initialize the input stream for benchmarking
        inputStream = new ByteArrayInputStream(compressedData);
    }

    // --- Benchmarks ---

    /**
     * Benchmark for standard single GZIP decompression.
     * Measures the time taken to decompress a single, complete GZIP stream.
     */
    @Benchmark
    public void benchmarkDecompressSingle(Blackhole bh) throws IOException {
        // Create the GzipCompressorInputStream wrapping the input stream
        GzipCompressorInputStream gzipInputStream = new GzipCompressorInputStream(inputStream);

        // Read all decompressed data and consume the result
        byte[] decompressedData = IOUtils.toByteArray(gzipInputStream);
        bh.consume(decompressedData);
    }

    /**
     * Benchmark for decompression of concatenated GZIP streams.
     * This tests the logic path where decompressConcatenated is true.
     */
    @Benchmark
    public void benchmarkDecompressConcatenated(Blackhole bh) throws IOException {
        // Configure the stream to handle concatenation
        GzipCompressorInputStream gzipInputStream = new GzipCompressorInputStream(inputStream, true);

        // Read all decompressed data and consume the result
        byte[] decompressedData = IOUtils.toByteArray(gzipInputStream);
        bh.consume(decompressedData);
    }
}
