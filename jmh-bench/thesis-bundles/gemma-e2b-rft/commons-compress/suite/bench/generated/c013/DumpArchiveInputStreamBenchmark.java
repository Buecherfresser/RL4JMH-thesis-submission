package bench.generated.c013;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import java.util.concurrent.TimeUnit;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.Arrays;
import org.apache.commons.compress.archivers.dump.DumpArchiveInputStream;
import org.apache.commons.compress.archivers.dump.DumpArchiveEntry;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class DumpArchiveInputStreamBenchmark {

    private DumpArchiveInputStream inputStream;
    private byte[] archivePayload;

    // Constants for input size
    private static final int PAYLOAD_SIZE = 1024 * 1024 * 4; // 4MB payload

    @Setup
    public void setup() throws IOException {
        // --- Setup: Create a representative in-memory dump archive payload ---
        // NOTE: In a real scenario, this byte array would be generated by writing a valid
        // dump archive file. For this exercise, we create a large dummy array.
        this.archivePayload = new byte[PAYLOAD_SIZE];
        // Fill with some data to simulate a real archive structure
        Arrays.fill(archivePayload, (byte) 0xAA);

        try (InputStream is = new ByteArrayInputStream(archivePayload)) {
            // Initialize the subject under test
            this.inputStream = new DumpArchiveInputStream(is);
        }
    }

    @Benchmark
    public void benchmarkGetNextEntry(Blackhole bh) throws IOException {
        // Measure the time taken to read and parse the next archive entry.
        DumpArchiveEntry entry = inputStream.getNextEntry();
        bh.consume(entry);
    }

    @Benchmark
    public void benchmarkReadData(Blackhole bh) throws IOException {
        // Measure the time taken to read a chunk of data from the current entry.
        byte[] buffer = new byte[4096];
        int bytesRead = inputStream.read(buffer, 0, buffer.length);
        bh.consume(bytesRead);
    }

    @Benchmark
    public void benchmarkGetBytesRead(Blackhole bh) {
        // Measure the time taken to retrieve the total bytes read so far.
        long bytesRead = inputStream.getBytesRead();
        bh.consume(bytesRead);
    }
}
