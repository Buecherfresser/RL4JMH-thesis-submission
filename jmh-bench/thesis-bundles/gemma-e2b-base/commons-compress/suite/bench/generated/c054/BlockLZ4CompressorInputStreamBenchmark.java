package bench.generated.c054;

import org.apache.commons.compress.compressors.lz4.BlockLZ4CompressorInputStream;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.util.concurrent.TimeUnit;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
public class BlockLZ4CompressorInputStreamBenchmark {

    // Input data: A large byte array representing compressed LZ4 data.
    // In a real scenario, this would be generated by a separate LZ4 compressor.
    // We use a large, fixed payload to ensure the benchmark measures stream processing time.
    private byte[] compressedData;
    private ByteArrayInputStream inputStream;
    private BlockLZ4CompressorInputStream compressorInputStream;

    private static final int DATA_SIZE = 1024 * 1024; // 1 MB payload

    @Setup
    public void setup() throws IOException {
        // 1. Generate a fixed payload. For a real benchmark, this data must be valid LZ4 block format.
        // Here, we use random data as a placeholder for the compressed input stream.
        this.compressedData = new byte[DATA_SIZE];
        for (int i = 0; i < DATA_SIZE; i++) {
            compressedData[i] = (byte) (i % 256);
        }

        // 2. Initialize the input stream wrapper
        this.inputStream = new ByteArrayInputStream(compressedData);

        // 3. Initialize the subject under test
        this.compressorInputStream = new BlockLZ4CompressorInputStream(this.inputStream);
    }

    /**
     * Benchmark method to test reading a significant chunk of data from the stream.
     * This simulates decompression.
     */
    @Benchmark
    public void benchmarkReadLargeChunk(Blackhole bh) throws IOException {
        final int readLength = 1024 * 1024; // Read 1 MB
        byte[] buffer = new byte[readLength];
        
        int bytesRead = compressorInputStream.read(buffer, 0, readLength);
        
        if (bytesRead > 0) {
            bh.consume(buffer);
        }
    }

    /**
     * Benchmark method to test reading a small chunk of data.
     */
    @Benchmark
    public void benchmarkReadSmallChunk(Blackhole bh) throws IOException {
        final int readLength = 1024; // Read 1 KB
        byte[] buffer = new byte[readLength];
        
        int bytesRead = compressorInputStream.read(buffer, 0, readLength);
        
        if (bytesRead > 0) {
            bh.consume(buffer);
        }
    }
}
