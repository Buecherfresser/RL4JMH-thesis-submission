package bench.generated.c006;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.util.concurrent.TimeUnit;
import org.apache.commons.compress.archivers.arj.ArjArchiveInputStream;
import org.apache.commons.compress.archivers.arj.ArjArchiveEntry;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
public class ArjArchiveInputStreamBenchmark {

    private byte[] arjPayload;
    private ByteArrayInputStream inputStream;
    private ArjArchiveInputStream arjStream;

    // We need a way to reset the stream state for independent measurements.
    // Since ArjArchiveInputStream takes ownership of the stream, we must recreate it
    // or manage the state carefully. We will recreate it in setup for simplicity,
    // assuming the setup cost is acceptable relative to the benchmark cost.

    @Setup(Level.Trial)
    public void setup() throws Exception {
        // WARNING: Since we do not have the ArjArchiveOutputStream, we cannot generate a
        // valid ARJ file. We use a placeholder byte array and assume it represents a
        // valid ARJ archive containing at least one entry for benchmarking structure.
        // In a real scenario, this byte array would be generated by a known good writer.
        // We simulate a small payload.
        arjPayload = new byte[1024 * 10]; // 10 KB placeholder
    }

    /**
     * Benchmarks the cost of reading the next archive entry header.
     * This is a critical operation involving complex header parsing.
     */
    @Benchmark
    public ArjArchiveEntry benchmarkGetNextEntry(Blackhole bh) throws Exception {
        // Recreate the stream for each invocation to ensure a fresh state (start of archive)
        inputStream = new ByteArrayInputStream(arjPayload);
        arjStream = new ArjArchiveInputStream(inputStream);

        ArjArchiveEntry entry = arjStream.getNextEntry();
        
        // Consume the result
        bh.consume(entry);
        
        // Clean up resources
        arjStream.close();
        
        return entry;
    }

    /**
     * Benchmarks the cost of reading data from the current entry.
     * This requires the stream to be positioned on a valid entry.
     */
    @Benchmark
    public void benchmarkReadData(Blackhole bh) throws Exception {
        // Recreate the stream for each invocation
        inputStream = new ByteArrayInputStream(arjPayload);
        arjStream = new ArjArchiveInputStream(inputStream);

        // Advance to the first entry
        ArjArchiveEntry entry = arjStream.getNextEntry();
        
        if (entry == null) {
            // Should not happen with a valid payload, but handle defensively
            bh.consume(0);
            arjStream.close();
            return;
        }

        // Prepare buffer
        byte[] buffer = new byte[4096];
        
        // Read data
        int bytesRead = arjStream.read(buffer, 0, buffer.length);
        
        // Consume the result
        bh.consume(bytesRead);
        
        // Clean up resources
        arjStream.close();
    }

    /**
     * Benchmarks the cost of retrieving the archive's name metadata.
     * This typically happens during initialization but is exposed as a getter.
     */
    @Benchmark
    public String benchmarkGetArchiveName(Blackhole bh) throws Exception {
        // Recreate the stream for each invocation
        inputStream = new ByteArrayInputStream(arjPayload);
        arjStream = new ArjArchiveInputStream(inputStream);

        String name = arjStream.getArchiveName();
        
        // Consume the result
        bh.consume(name);
        
        // Clean up resources
        arjStream.close();
        
        return name;
    }

    /**
     * Benchmarks the cost of retrieving the archive's comment metadata.
     */
    @Benchmark
    public String benchmarkGetArchiveComment(Blackhole bh) throws Exception {
        // Recreate the stream for each invocation
        inputStream = new ByteArrayInputStream(arjPayload);
        arjStream = new ArjArchiveInputStream(inputStream);

        String comment = arjStream.getArchiveComment();
        
        // Consume the result
        bh.consume(comment);
        
        // Clean up resources
        arjStream.close();
        
        return comment;
    }
}
