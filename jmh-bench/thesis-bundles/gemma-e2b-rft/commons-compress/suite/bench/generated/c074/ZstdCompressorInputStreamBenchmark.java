package bench.generated.c074;

import org.apache.commons.compress.compressors.zstandard.ZstdCompressorInputStream;
import org.apache.commons.io.IOUtils;
import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.concurrent.TimeUnit;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class ZstdCompressorInputStreamBenchmark {

    private InputStream compressedDataStream;
    private ZstdCompressorInputStream zstdInputStream;
    private byte[] decompressedData;
    private final int PAYLOAD_SIZE = 1024 * 1024; // 1MB payload size

    @Setup
    public void setup() throws IOException {
        // --- 1. Create a representative compressed payload ---
        // NOTE: In a real scenario, this byte array would be generated by compressing
        // actual data using Zstd. For this benchmark structure, we use a fixed size
        // of dummy data to simulate the compressed input stream.
        byte[] rawData = new byte[PAYLOAD_SIZE];
        // Fill with some non-zero data to simulate compressed content
        for (int i = 0; i < PAYLOAD_SIZE; i++) {
            rawData[i] = (byte) (i % 256);
        }

        this.compressedDataStream = new ByteArrayInputStream(rawData);

        // --- 2. Initialize the subject under test ---
        this.zstdInputStream = new ZstdCompressorInputStream(compressedDataStream);

        // --- 3. Pre-calculate the expected decompressed size (for validation/context) ---
        // Since we don't have the actual decompression logic here, we simulate the output size.
        // In a real test, we would decompress the rawData to get decompressedData.
        // For simplicity in this structure, we assume the decompressed size is roughly the same
        // or slightly larger, but we must ensure we have a result to consume.
        this.decompressedData = new byte[PAYLOAD_SIZE * 2]; // Simulate double size for reading tests
    }

    @Benchmark
    public void readSingleByte(Blackhole bh) throws IOException {
        int result = zstdInputStream.read();
        bh.consume(result);
    }

    @Benchmark
    public void readBuffer(Blackhole bh) throws IOException {
        byte[] buffer = new byte[4096];
        int bytesRead = zstdInputStream.read(buffer);
        bh.consume(bytesRead);
    }

    @Benchmark
    public void readSegment(Blackhole bh) throws IOException {
        byte[] buffer = new byte[1024];
        int bytesRead = zstdInputStream.read(buffer, 0, buffer.length);
        bh.consume(bytesRead);
    }

    @Benchmark
    public void getCompressedCount(Blackhole bh) {
        long count = zstdInputStream.getCompressedCount();
        bh.consume(count);
    }

    @Benchmark
    public void skipBytes(Blackhole bh) throws IOException {
        long skipAmount = PAYLOAD_SIZE / 10;
        long skipped = zstdInputStream.skip(skipAmount);
        bh.consume(skipped);
    }

    @Benchmark
    public void closeStream(Blackhole bh) throws IOException {
        zstdInputStream.close();
        bh.consume(null);
    }
}
