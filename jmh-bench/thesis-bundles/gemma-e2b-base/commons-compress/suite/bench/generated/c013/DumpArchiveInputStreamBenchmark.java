package bench.generated.c013;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.Arrays;
import java.util.concurrent.TimeUnit;

import org.apache.commons.compress.archivers.ArchiveInputStream;
import org.apache.commons.compress.archivers.dump.DumpArchiveEntry;
import org.apache.commons.compress.archivers.dump.DumpArchiveInputStream;
import org.apache.commons.compress.utils.IOUtils;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class DumpArchiveInputStreamBenchmark {

    // --- Setup Fields ---
    private byte[] archivePayload;
    private InputStream inputStream;
    private DumpArchiveInputStream dumpInputStream;

    // Constants for input size (must be large enough to measure overhead, small enough to run fast)
    private static final int PAYLOAD_SIZE = 1024 * 1024 * 4; // 4 MB payload

    @Setup(Level.Trial)
    public void setup() throws IOException {
        // 1. Create a large, representative payload.
        // NOTE: In a real scenario, this byte array would be generated by writing a valid dump archive.
        // Here, we use random data to simulate a large file structure for benchmarking stream processing overhead.
        this.archivePayload = new byte[PAYLOAD_SIZE];
        new java.util.Random().nextBytes(this.archivePayload);

        this.inputStream = new ByteArrayInputStream(this.archivePayload);

        // 2. Initialize the subject under test.
        // We use the default constructor (platform encoding) for simplicity.
        this.dumpInputStream = new DumpArchiveInputStream(this.inputStream);
    }

    // --- Benchmarks ---

    /**
     * Benchmark for initializing the DumpArchiveInputStream from an InputStream.
     */
    @Benchmark
    public void benchmarkInitialization(Blackhole bh) throws IOException {
        // Re-initialize the stream for each run to measure construction overhead.
        try (InputStream tempStream = new ByteArrayInputStream(archivePayload)) {
            DumpArchiveInputStream tempStreamInstance = new DumpArchiveInputStream(tempStream);
            bh.consume(tempStreamInstance);
        }
    }

    /**
     * Benchmark for reading the next archive entry.
     * This tests the logic involving queue management and header parsing.
     */
    @Benchmark
    public void benchmarkGetNextEntry(Blackhole bh) throws IOException {
        // Use the pre-initialized stream instance from setup
        DumpArchiveEntry entry = dumpInputStream.getNextEntry();
        bh.consume(entry);
    }

    /**
     * Benchmark for reading data from the current entry using the read method.
     * This tests the core data extraction and buffer management logic.
     */
    @Benchmark
    public void benchmarkReadData(Blackhole bh) throws IOException {
        // Ensure we are positioned at the start of an entry (or rely on the stream state)
        byte[] readBuffer = new byte[4096];
        int bytesRead = dumpInputStream.read(readBuffer, 0, readBuffer.length);
        bh.consume(bytesRead);
    }

    /**
     * Benchmark for closing the stream.
     */
    @Benchmark
    public void benchmarkClose(Blackhole bh) throws IOException {
        dumpInputStream.close();
        bh.consume(null);
    }
}
