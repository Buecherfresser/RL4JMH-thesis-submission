package bench.generated.c029;

import org.apache.commons.compress.archivers.tar.TarArchiveEntry;
import org.apache.commons.compress.archivers.tar.TarFile;
import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.Arrays;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class TarFileBenchmark {

    private byte[] tarArchiveData;
    private TarFile tarFile;
    private List<TarArchiveEntry> entries;

    /**
     * Setup method: Builds a representative, in-memory TAR archive payload.
     * Since generating a fully valid TAR structure is complex, this setup creates a large,
     * structured byte array to simulate a real archive for parsing tests.
     */
    @Setup
    public void setup() throws IOException {
        // --- Payload Generation Simulation ---
        // In a real scenario, this byte array would be generated by writing a valid TAR file.
        // Here, we create a large, structured byte array to test the parsing overhead of TarFile.
        // We use a large buffer to ensure the benchmark measures parsing complexity, not just trivial operations.
        int payloadSize = 1024 * 1024 * 5; // 5 MB payload
        byte[] content = new byte[payloadSize];
        
        // Fill with some structured data to simulate headers and content blocks
        for (int i = 0; i < payloadSize; i++) {
            content[i] = (byte) (i % 256);
        }
        
        this.tarArchiveData = content;

        // Initialize the TarFile object once for read benchmarks
        this.tarFile = new TarFile(tarArchiveData);
        this.entries = this.tarFile.getEntries();
    }

    /**
     * Benchmark 1: Measures the time taken to construct a TarFile instance from a byte array.
     */
    @Benchmark
    public void constructTarFile(Blackhole bh) throws IOException {
        // Re-instantiate TarFile in every run to measure construction time
        TarFile tempFile = new TarFile(tarArchiveData);
        bh.consume(tempFile);
    }

    /**
     * Benchmark 2: Measures the time taken to retrieve all entries from the TarFile.
     */
    @Benchmark
    public void getEntries(Blackhole bh) {
        // Use the pre-initialized tarFile from setup
        bh.consume(tarFile.getEntries());
    }

    /**
     * Benchmark 3: Measures the time taken to retrieve a specific entry's input stream.
     * We select the first entry for this test.
     */
    @Benchmark
    public void getInputStream(Blackhole bh) throws IOException {
        if (!entries.isEmpty()) {
            TarArchiveEntry firstEntry = entries.get(0);
            // Measure the time taken to create the stream wrapper and read from it
            try (InputStream entryStream = tarFile.getInputStream(firstEntry)) {
                // Drain the stream to ensure the stream creation logic is fully executed
                byte[] result = new byte[1024];
                int read = entryStream.read(result);
                bh.consume(read);
            }
        }
    }
}
