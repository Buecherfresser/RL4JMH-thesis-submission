package bench.generated.c046;

import org.apache.commons.compress.compressors.deflate.DeflateCompressorInputStream;
import org.apache.commons.compress.compressors.deflate.DeflateParameters;
import org.apache.commons.io.IOUtils;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.concurrent.TimeUnit;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
public class DeflateCompressorInputStreamBenchmark {

    private InputStream compressedDataStream;
    private byte[] compressedPayload;
    private DeflateCompressorInputStream deflateInputStream;

    // Fixed payload for benchmarking. This must be a valid Deflate compressed stream.
    // For a real benchmark, this payload would be generated by a compression utility.
    // Using a small, fixed byte array here to simulate a compressed input.
    private static final byte[] FIXED_PAYLOAD = {
        (byte) 0x78, (byte) 0x01, (byte) 0x5e, (byte) 0x9c, (byte) 0xda,
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19
    };

    @Setup
    public void setup() throws IOException {
        this.compressedPayload = FIXED_PAYLOAD;
        this.compressedDataStream = new ByteArrayInputStream(compressedPayload);
        
        // Initialize the stream using the constructor that takes only the InputStream
        this.deflateInputStream = new DeflateCompressorInputStream(compressedDataStream);
    }

    @Benchmark
    public void readSingleByte(Blackhole bh) throws IOException {
        int result = deflateInputStream.read();
        bh.consume(result);
    }

    @Benchmark
    public void readChunk(Blackhole bh) throws IOException {
        byte[] buffer = new byte[1024];
        int result = deflateInputStream.read(buffer, 0, buffer.length);
        bh.consume(result);
    }

    @Benchmark
    public void skipData(Blackhole bh) throws IOException {
        long skipAmount = 1024;
        long skipped = deflateInputStream.skip(skipAmount);
        bh.consume(skipped);
    }

    @Benchmark
    public void checkAvailable(Blackhole bh) throws IOException {
        int available = deflateInputStream.available();
        bh.consume(available);
    }

    @Benchmark
    public void getCompressedCount(Blackhole bh) {
        long count = deflateInputStream.getCompressedCount();
        bh.consume(count);
    }

    @Benchmark
    public void closeStream(Blackhole bh) throws IOException {
        deflateInputStream.close();
        // No return value, consume is implicit if we don't return, but we ensure the call happens.
    }
}
