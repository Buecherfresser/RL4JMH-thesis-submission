package bench.generated.c049;

import org.apache.commons.compress.compressors.deflate64.Deflate64CompressorInputStream;
import org.apache.commons.io.IOUtils;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.concurrent.TimeUnit;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class Deflate64CompressorInputStreamBenchmark {

    private byte[] compressedPayload;
    private InputStream inputStream;
    private Deflate64CompressorInputStream compressorInputStream;

    // Define a representative payload size (e.g., 100 KB)
    private static final int PAYLOAD_SIZE = 1024 * 100;

    @Setup
    public void setup() throws IOException {
        // --- Input Generation ---
        // In a real scenario, this payload would be generated by compressing data.
        // For this benchmark, we create a byte array of fixed size.
        // NOTE: This byte array is NOT guaranteed to be valid Deflate64 compressed data,
        // but it serves as a fixed, non-final input fixture as required by JMH rules.
        this.compressedPayload = new byte[PAYLOAD_SIZE];
        // Fill with some data to ensure the stream has content
        for (int i = 0; i < PAYLOAD_SIZE; i++) {
            compressedPayload[i] = (byte) (i % 256);
        }

        this.inputStream = new ByteArrayInputStream(compressedPayload);

        // --- SUT Initialization ---
        // Initialize the Deflate64CompressorInputStream using the input stream.
        this.compressorInputStream = new Deflate64CompressorInputStream(this.inputStream);
    }

    @Benchmark
    public void readSingleByte(Blackhole bh) throws IOException {
        // Test the basic read() method
        int result = compressorInputStream.read();
        bh.consume(result);
    }

    @Benchmark
    public void readChunk(Blackhole bh) throws IOException {
        // Test the read(byte[], off, len) method with a medium chunk size
        byte[] buffer = new byte[1024];
        int result = compressorInputStream.read(buffer, 0, buffer.length);
        bh.consume(result);
    }

    @Benchmark
    public void readLargeChunk(Blackhole bh) throws IOException {
        // Test the read(byte[], off, len) method with a large chunk size
        byte[] buffer = new byte[8192];
        int result = compressorInputStream.read(buffer, 0, buffer.length);
        bh.consume(result);
    }

    @Benchmark
    public void closeStream(Blackhole bh) throws IOException {
        // Test the close() method, which should clean up resources
        compressorInputStream.close();
        bh.consume(null);
    }

    @Benchmark
    public void getCompressedCount(Blackhole bh) {
        // Test the statistics method
        long count = compressorInputStream.getCompressedCount();
        bh.consume(count);
    }
}
