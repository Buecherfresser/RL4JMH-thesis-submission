package bench.generated.c054;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import java.util.concurrent.TimeUnit;
import java.io.ByteArrayInputStream;
import java.io.InputStream;
import org.apache.commons.compress.compressors.lz4.BlockLZ4CompressorInputStream;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
public class BlockLZ4CompressorInputStreamBenchmark {

    // Placeholder for a small, representative compressed LZ4 block payload.
    // In a real scenario, this byte array would be generated by compressing a known input.
    // We use a small array to ensure fast setup and execution.
    private byte[] compressedPayload;
    private InputStream inputStream;

    @Setup(Level.Trial)
    public void setup() {
        // Simulate a small compressed payload (e.g., 100 bytes of compressed data)
        // Note: This data is NOT guaranteed to be valid LZ4 block format, but serves
        // to structure the benchmark correctly around the SUT usage.
        compressedPayload = new byte[100];
        for (int i = 0; i < 100; i++) {
            compressedPayload[i] = (byte) (i % 256);
        }
        inputStream = new ByteArrayInputStream(compressedPayload);
    }

    /**
     * Benchmarks the initial read operation and state transition of the decompressor.
     * This measures the time taken to process the first chunk of compressed data.
     */
    @Benchmark
    public void readFirstChunk(Blackhole bh) throws Exception {
        // Since the stream is stateful, we must create a fresh instance for each benchmark run
        // if we want to measure the cost of starting the decompression process from scratch.
        // However, to measure sustained performance, we reuse the stream instance across calls
        // if we were running a loop. For a single invocation benchmark, we create it here.
        
        // To ensure the benchmark measures the SUT's performance, we instantiate it inside the method
        // or manage its lifecycle carefully. Since the input stream is fixed, we instantiate it here.
        BlockLZ4CompressorInputStream lz4Stream = new BlockLZ4CompressorInputStream(inputStream);
        
        byte[] buffer = new byte[10];
        
        // Call the subject method exactly once
        int bytesRead = lz4Stream.read(buffer, 0, 10);
        
        // Consume the result
        bh.consume(bytesRead);
    }

    /**
     * Benchmarks sustained reading performance by repeatedly calling read() on the same stream instance.
     * This measures the throughput of the decompressor over multiple calls.
     */
    @Benchmark
    public void sustainedRead(Blackhole bh) throws Exception {
        // Instantiate the stream once per benchmark run (Trial scope)
        BlockLZ4CompressorInputStream lz4Stream = new BlockLZ4CompressorInputStream(inputStream);
        
        byte[] buffer = new byte[10];
        int totalBytesRead = 0;
        
        // Loop to drain the stream, simulating continuous reading
        while (true) {
            // Call the subject method exactly once per loop iteration
            int bytesRead = lz4Stream.read(buffer, 0, 10);
            
            if (bytesRead == -1) {
                break;
            }
            totalBytesRead += bytesRead;
        }
        
        // Consume the final result
        bh.consume(totalBytesRead);
    }
}
