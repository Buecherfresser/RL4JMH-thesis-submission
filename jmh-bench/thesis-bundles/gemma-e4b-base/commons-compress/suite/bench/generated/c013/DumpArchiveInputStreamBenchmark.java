package bench.generated.c013;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.util.concurrent.TimeUnit;
import org.apache.commons.compress.archivers.dump.DumpArchiveInputStream;
import org.apache.commons.compress.archivers.dump.DumpArchiveEntry;
import org.apache.commons.compress.archivers.dump.DumpArchiveSummary;
import org.apache.commons.compress.archivers.dump.DumpArchiveConstants;
import org.apache.commons.compress.archivers.dump.UnrecognizedFormatException;
import org.apache.commons.compress.archivers.dump.InvalidFormatException;
import org.apache.commons.compress.archivers.dump.DumpArchiveException;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
public class DumpArchiveInputStreamBenchmark {

    private byte[] dumpArchivePayload;
    private final int BUFFER_SIZE = 4096;

    /**
     * Setup prepares a representative, fixed input payload (a mock dump archive).
     * Since generating a real dump archive is complex, we use a placeholder byte array
     * and assume it represents a valid archive for benchmarking the stream logic.
     */
    @Setup(Level.Trial)
    public void setup() {
        // Mock payload: A small byte array representing a dump archive.
        // In a real scenario, this would be generated by writing a valid dump file.
        // We ensure it is large enough to pass the initial header check (32 bytes).
        dumpArchivePayload = new byte[1024 * 10]; // 10 KB mock archive
        // Fill with some data to simulate content
        for (int i = 0; i < dumpArchivePayload.length; i++) {
            dumpArchivePayload[i] = (byte) (i % 256);
        }
    }

    /**
     * Benchmarks the operation of reading the next entry from the dump archive.
     * This tests the core logic of parsing headers and managing the entry queue.
     */
    @Benchmark
    public DumpArchiveEntry benchmarkGetNextEntry(Blackhole bh) throws IOException {
        // Must create a fresh instance for each invocation due to state mutation
        ByteArrayInputStream bais = new ByteArrayInputStream(dumpArchivePayload);
        DumpArchiveInputStream stream = new DumpArchiveInputStream(bais, null);

        DumpArchiveEntry entry = stream.getNextEntry();

        // Consume the result
        bh.consume(entry);

        // Clean up resources
        stream.close();
        return entry;
    }

    /**
     * Benchmarks reading a chunk of data from the current entry.
     * This tests the internal buffering and record reading logic.
     */
    @Benchmark
    public int benchmarkReadData(Blackhole bh) throws IOException {
        // Must create a fresh instance for each invocation due to state mutation
        ByteArrayInputStream bais = new ByteArrayInputStream(dumpArchivePayload);
        DumpArchiveInputStream stream = new DumpArchiveInputStream(bais, null);

        // Ensure we have an entry to read from
        DumpArchiveEntry entry = stream.getNextEntry();
        if (entry == null) {
            // If the mock payload is too small to yield an entry, skip or handle gracefully
            stream.close();
            return 0;
        }

        byte[] buffer = new byte[BUFFER_SIZE];
        int bytesRead = stream.read(buffer, 0, BUFFER_SIZE);

        // Consume the result
        bh.consume(bytesRead);

        // Clean up resources
        stream.close();
        return bytesRead;
    }
}
