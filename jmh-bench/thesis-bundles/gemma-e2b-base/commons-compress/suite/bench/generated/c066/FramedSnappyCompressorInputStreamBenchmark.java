package bench.generated.c066;

import org.apache.commons.compress.compressors.snappy.FramedSnappyCompressorInputStream;
import org.apache.commons.compress.compressors.snappy.FramedSnappyDialect;
import org.apache.commons.io.IOUtils;
import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.Arrays;
import java.util.concurrent.TimeUnit;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
public class FramedSnappyCompressorInputStreamBenchmark {

    private InputStream input;
    private FramedSnappyCompressorInputStream stream;
    private byte[] payload;
    private final int BLOCK_SIZE = 1024;

    @Setup
    public void setup() throws IOException {
        // --- 1. Create a representative payload ---
        // Since we don't have the compressor, we create a minimal, valid-looking byte array.
        // In a real scenario, this payload would be generated by a Snappy compressor.
        // We use a small, repeating pattern to ensure the stream has some structure.
        byte[] rawData = new byte[1024 * 10]; // 10KB of data
        for (int i = 0; i < rawData.length; i++) {
            rawData[i] = (byte) (i % 256);
        }
        this.payload = rawData;

        // --- 2. Prepare the input stream ---
        this.input = new ByteArrayInputStream(payload);

        // --- 3. Prepare the FramedSnappyCompressorInputStream instance ---
        // We use the constructor that takes the InputStream directly.
        this.stream = new FramedSnappyCompressorInputStream(this.input);
    }

    @Benchmark
    public void readSingleByte(Blackhole bh) throws IOException {
        int result = stream.read();
        bh.consume(result);
    }

    @Benchmark
    public void readBulk(Blackhole bh) throws IOException {
        byte[] buffer = new byte[1024];
        int result = stream.read(buffer, 0, buffer.length);
        bh.consume(result);
    }

    @Benchmark
    public void closeStream(Blackhole bh) throws IOException {
        stream.close();
        bh.consume(null);
    }

    @Benchmark
    public void availableCheck(Blackhole bh) throws IOException {
        int available = stream.available();
        bh.consume(available);
    }

    @Benchmark
    public void constructorWithBlockSize(Blackhole bh) throws IOException {
        // Re-initialize stream for this test to ensure clean state if needed,
        // although @State should handle this. We use a fresh input stream for safety.
        InputStream freshInput = new ByteArrayInputStream(payload);
        FramedSnappyDialect dialect = FramedSnappyDialect.STANDARD;
        FramedSnappyCompressorInputStream freshStream = new FramedSnappyCompressorInputStream(freshInput, BLOCK_SIZE, dialect);
        bh.consume(freshStream);
    }

    @Benchmark
    public void constructorWithDialect(Blackhole bh) throws IOException {
        // Re-initialize stream for this test
        InputStream freshInput = new ByteArrayInputStream(payload);
        FramedSnappyDialect dialect = FramedSnappyDialect.STANDARD;
        FramedSnappyCompressorInputStream freshStream = new FramedSnappyCompressorInputStream(freshInput, 1024, dialect);
        bh.consume(freshStream);
    }
}
