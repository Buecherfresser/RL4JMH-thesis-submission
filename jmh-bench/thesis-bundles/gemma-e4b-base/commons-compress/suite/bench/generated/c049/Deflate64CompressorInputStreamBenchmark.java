package bench.generated.c049;

import org.openjdk.jmh.annotations.*;
import org.openjdk.jmh.infra.Blackhole;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.concurrent.TimeUnit;

import org.apache.commons.compress.compressors.deflate64.Deflate64CompressorInputStream;

@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Fork(1)
@Warmup(iterations = 1, time = 1)
@Measurement(iterations = 3, time = 1)
public class Deflate64CompressorInputStreamBenchmark {

    // Placeholder for a representative compressed payload.
    // In a real scenario, this would be generated by Deflate64CompressorOutputStream.
    private byte[] compressedPayload;

    @Setup(Level.Trial)
    public void setup() {
        // Using a small, fixed payload for benchmarking purposes.
        // This byte array must represent valid Deflate64 compressed data.
        // Since we cannot run the compressor here, we use a dummy array.
        // The benchmark measures the decompression logic on this input.
        compressedPayload = new byte[]{
                (byte) 0x78, (byte) 0x9C, (byte) 0x03, (byte) 0x00, (byte) 0x00, (byte) 0x00,
                (byte) 0x00, (byte) 0x00, (byte) 0x00, (byte) 0x00, (byte) 0x00, (byte) 0x00
        };
    }

    /**
     * Benchmarks reading a single byte using read().
     */
    @Benchmark
    public int benchmarkReadSingleByte(Blackhole bh) throws IOException {
        // Recreate the stream for each invocation to ensure a clean state
        try (InputStream is = new ByteArrayInputStream(compressedPayload);
             Deflate64CompressorInputStream dic = new Deflate64CompressorInputStream(is)) {
            
            int result = dic.read();
            bh.consume(result);
            return result;
        }
    }

    /**
     * Benchmarks reading a bulk amount of bytes using read(byte[], int, int).
     */
    @Benchmark
    public int benchmarkReadBulkBytes(Blackhole bh) throws IOException {
        final int bufferSize = 1024;
        byte[] buffer = new byte[bufferSize];

        // Recreate the stream for each invocation
        try (InputStream is = new ByteArrayInputStream(compressedPayload);
             Deflate64CompressorInputStream dic = new Deflate64CompressorInputStream(is)) {

            int result = dic.read(buffer, 0, bufferSize);
            bh.consume(result);
            return result;
        }
    }

    /**
     * Benchmarks checking the number of available bytes remaining in the stream.
     */
    @Benchmark
    public void benchmarkAvailable(Blackhole bh) throws IOException {
        // Recreate the stream for each invocation
        try (InputStream is = new ByteArrayInputStream(compressedPayload);
             Deflate64CompressorInputStream dic = new Deflate64CompressorInputStream(is)) {

            int available = dic.available();
            bh.consume(available);
        }
    }

    /**
     * Benchmarks retrieving the count of compressed bytes read so far.
     */
    @Benchmark
    public void benchmarkGetCompressedCount(Blackhole bh) throws IOException {
        // Recreate the stream for each invocation
        try (InputStream is = new ByteArrayInputStream(compressedPayload);
             Deflate64CompressorInputStream dic = new Deflate64CompressorInputStream(is)) {

            long count = dic.getCompressedCount();
            bh.consume(count);
        }
    }

    /**
     * Benchmarks the stream closing operation.
     */
    @Benchmark
    public void benchmarkClose(Blackhole bh) throws IOException {
        // Recreate the stream for each invocation
        try (InputStream is = new ByteArrayInputStream(compressedPayload);
             Deflate64CompressorInputStream dic = new Deflate64CompressorInputStream(is)) {

            dic.close();
            bh.consume(true); // Consume result to prevent dead code elimination
        }
    }
}
